export const USDA_FDC_SR_LEGACY_URL = "https://fdc.nal.usda.gov/download-datasets/";

type CuratedEstimate = Extract<Provenance, { kind: "curated_estimate" }>;

function fdcRecord(fdcId: number, recordDescription: string): FoodDataCentralRecord {
  return { fdcId, recordDescription, sourceUrl: USDA_FDC_SR_LEGACY_URL };
}

function usdaFdcSource(fdcId: number, recordDescription: string): Provenance {
  return {
    kind: "usda",
    ...fdcRecord(fdcId, recordDescription),
    checkedAt,
  };
}

function usdaFdcProxySource(
  fdcId: number,
  recordDescription: string,
  ingredientDescription: string,
): CuratedEstimate {
  return {
    kind: "curated_estimate",
    checkedAt,
    reference: fdcRecord(fdcId, recordDescription),
    explanation: `USDA FoodData Central SR Legacy FDC ID ${fdcId} (${recordDescription}) is used without nutrient adjustment as a proxy for ${ingredientDescription} because the release has no exact record for this cultivar or product form. The actual Thai ingredient may differ.`,
  };
}

